#!/usr/bin/env node
/**
 * Scans one folder per highlight card and writes js/gallery-categories.js
 * with a GALLERY_CATEGORIES object keyed by category. Both the highlight
 * card (cycling preview) and its full gallery page read from this file —
 * there is nothing else to edit.
 *
 * Run manually whenever you add or remove images: node scripts/build-gallery-categories.js
 *
 * Filename → caption: hyphens/underscores/camelCase become spaces, words are
 * capitalised. Example: "TokyoGlow.webp" → "Tokyo Glow".
 */

const fs   = require('fs');
const path = require('path');

const ROOT     = path.join(__dirname, '..');
const OUT_FILE = path.join(ROOT, 'js', 'gallery-categories.js');

const CATEGORIES = [
  { key: 'drinks',   dir: 'assets/drinks'  },
  { key: 'beer',     dir: 'assets/beer'    },
  { key: 'desserts', dir: 'assets/Dessert' },
  { key: 'kitchen',  dir: 'assets/Entrees' },
];

const SUPPORTED = new Set(['.webp', '.jpg', '.jpeg', '.png', '.gif', '.avif']);

function toAlt(filename) {
  return filename
    .replace(/\.[^.]+$/, '')                 // strip extension
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')  // camelCase -> camel Case
    .replace(/[-_]+/g, ' ')                  // dashes/underscores -> spaces
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/\b\w/g, c => c.toUpperCase()); // Title Case
}

const result = {};

CATEGORIES.forEach(({ key, dir }) => {
  const abs = path.join(ROOT, dir);
  const files = fs.existsSync(abs)
    ? fs.readdirSync(abs).filter(f => SUPPORTED.has(path.extname(f).toLowerCase())).sort()
    : [];

  if (!files.length) {
    console.warn(`build-gallery-categories: no images found in ${dir}/`);
  }

  result[key] = files.map(f => ({ img: `${dir}/${f}`, alt: toAlt(f) }));
});

const lines = ['const GALLERY_CATEGORIES = {'];
CATEGORIES.forEach(({ key }) => {
  lines.push(`  ${key}: ${JSON.stringify(result[key], null, 2).replace(/\n/g, '\n  ')},`);
});
lines.push('};', '');

const output = [
  '/* ============================================================',
  '   Canton Dragon — per-category gallery pages',
  '   Auto-generated by scripts/build-gallery-categories.js — do not edit here.',
  '   Add / remove images in the folder for each category, then re-run:',
  '     node scripts/build-gallery-categories.js',
  '   Powers both the highlight card (cycling preview) on index.html and',
  '   its matching gallery-*.html page.',
  '   ============================================================ */',
  lines.join('\n'),
].join('\n');

fs.writeFileSync(OUT_FILE, output, 'utf8');
CATEGORIES.forEach(({ key }) => {
  console.log(`build-gallery-categories: ${key} — ${result[key].length} image(s)`);
});
console.log('build-gallery-categories: wrote js/gallery-categories.js');
